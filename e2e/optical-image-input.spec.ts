import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { expect, test } from '@playwright/test';
import { encodePng } from '../scripts/png';

test('local image preparation preserves grayscale pixels and records target coordinates without uploading', async ({ page }) => {
  const html = readFileSync(fileURLToPath(new URL('../tools/optical-image-input.html', import.meta.url)), 'utf8');
  const requests: string[] = [];
  page.on('request', (request) => requests.push(request.url()));
  await page.route('**/optical-image-input', (route) => route.fulfill({ contentType: 'text/html', body: html }));
  await page.goto('/optical-image-input');
  const navigationUrl = page.url();
  const pixels = Uint8Array.from({ length: 120 * 80 }, (_, i) => i % 256);
  await page.locator('#image').setInputFiles({ name: 'test-print.png', mimeType: 'image/png', buffer: encodePng(120, 80, pixels) });
  await expect(page.locator('#info')).toContainText('120 × 80px');
  await expect(page.locator('#download')).toBeEnabled();
  const bounds = await page.locator('#preview').boundingBox();
  expect(bounds).not.toBeNull();
  await page.mouse.move(bounds!.x + 20, bounds!.y + 10);
  await page.mouse.down();
  await page.mouse.move(bounds!.x + 90, bounds!.y + 60);
  await page.mouse.up();
  expect(JSON.parse(await page.locator('#region').inputValue())).toEqual({ xMin: 20, yMin: 10, xMax: 90, yMax: 60 });
  const regionPixels = Array.from({ length: 50 }, (_, y) => Array.from(pixels.subarray((y + 10) * 120 + 20, (y + 10) * 120 + 90))).flat();
  const mean = (regionPixels.reduce((sum, value) => sum + value, 0) / regionPixels.length).toFixed(2);
  await expect(page.locator('#roi-stats')).toContainText(`평균 ${mean}`);
  const downloaded = page.waitForEvent('download');
  await page.locator('#download').click();
  const file = await downloaded;
  expect(file.suggestedFilename()).toBe('test-print.pgm');
  const chunks: Buffer[] = [];
  const stream = await file.createReadStream();
  for await (const chunk of stream) chunks.push(Buffer.from(chunk));
  const data = Buffer.concat(chunks);
  const header = Buffer.from('P5\n120 80\n255\n');
  expect(data.subarray(0, header.length)).toEqual(header);
  expect(data.subarray(header.length)).toEqual(Buffer.from(pixels));
  expect(requests).toEqual([navigationUrl]);
});
